.data
array: .space 100       # Выделяем память (19 чисел * 4 байта = 76 байт, берем 100 с запасом)
prompt: .asciz "Вводите числа (0 для остановки, максимум 19):\n"
size_msg: .asciz "Итоговый размер массива: "
newline: .asciz "\n"
N_val: .word 3          # Твой номер в списке = 3
                        # Размер массива = 16 + 3 = 19

.text
.globl main
main:
    # Выводим приглашение
    la a0, prompt
    li a7, 4
    ecall

    li t0, 0            # t0 = счетчик (i)
    
    # Вычисляем 16 + n
    la t1, N_val
    lw t1, 0(t1)
    addi t1, t1, 16     # t1 = 16 + 3 = 19 (максимальный размер)
    
    la t2, array        # t2 = адрес начала массива

read_loop:
    # Проверяем, не достигли ли лимита 19
    bge t0, t1, end_read

    # Считываем число
    li a7, 5
    ecall
    mv t3, a0           # t3 = введенное число

    # Если введен 0 - завершаем чтение
    beqz t3, end_read

    # Сохраняем число в массив
    slli t4, t0, 2      # t4 = i * 4 (умножаем индекс на размер слова)
    add t4, t2, t4      # t4 = адрес array[i]
    sw t3, 0(t4)        # Сохраняем слово

    # Увеличиваем счетчик
    addi t0, t0, 1
    j read_loop

end_read:
    # Выводим сообщение
    la a0, size_msg
    li a7, 4
    ecall

    # Выводим итоговый размер массива (сколько чисел реально считано)
    mv a0, t0
    li a7, 1
    ecall

    # Новая строка
    la a0, newline
    li a7, 4
    ecall

    # Завершение
    li a7, 10
    ecall